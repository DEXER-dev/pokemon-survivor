export const skillForm = (family, tier) => {
    const skill = SKILL_INFO[family];
    if (!skill) return null;
    const form = skill.forms[Math.max(0, Math.min(skill.forms.length - 1, (tier | 0) - 1))];
    return { line: skill.line, name: form[0], description: form[1] };
};

